// Package agentdetect 实现本机 agent 四层只读检测模型（v3 W06-01）：
// installed / config_recognized / execution_ready / call_allowed，每层独立记录
// 检查来源、检查时间（UTC）、能力版本信息与未验证原因。
//
// # 定位与红线
//
// 本包只做本机只读检测，零 REST 接线（接线属 W06-02）：不调用模型、不做登录
// 探针、不扫描磁盘、不读真实用户 HOME（测试全用 t.TempDir）、不返回任何文件
// 内容。HOME 配置只回「是否可用 + 引用路径」，秘密内容永不返回；命令探测只
// 运行「调用方显式给出的命令」的 --version，绝不运行模型、绝不 shell 拼接。
// call_allowed 来自调用方传入的授权投影，本包不判定、只承载（W06-02 定义
// 「允许本机调用」与 exposed 远端开放的差异）。
//
// # 四层判定规则（未运行不推断下一层）
//
//   - Installed：命令路径存在（Lstat 不跟随符号链接做存在判定）**且**
//     `<command> --version` 子进程退出码 0。命令必须是调用方显式给出的绝对
//     路径——裸名/相对路径直接拒绝（不做 PATH 搜索，不构成扫描证据）。探测
//     超时、非零退出、输出超限均判 Installed=false 并留原因。
//   - ConfigRecognized：已知宿主配置文件在受控 config_home 内按已知布局存在、
//     且结构可识别。结构可识别 ≠ 登录成功 ≠ 版本可用。符号链接一律不跟随
//     （如实注记 symlink，不读取、不展开）；非普通文件（目录/FIFO 等）不打开。
//   - ExecutionReady：前两层全过 **且** 发现宿主登录态标记，附显式注记
//     「执行前置检查通过（模型未验证）」。绝不声称账号/额度可用——未运行真实
//     模型探针（探针是主人显式动作，属 W06-02 的 /probe 端点），登录标记只是
//     结构线索，其有效性未验证。任何一层未检测（not_checked）则本层也
//     not_checked；任一层 fail 则本层 fail，配置可识别不推断可执行。
//   - CallAllowed：纯透传调用方投影（Allowed/Source/Reason 原样承载），本包
//     不产生任何判定证据。
//
// # 支持宿主表（未知宿主一律「通用手动」，不冒认已适配）
//
//	宿主    │ --version 判定        │ 配置位置                        │ 结构识别规则                          │ 登录态标记
//	────────┼───────────────────────┼─────────────────────────────────┼───────────────────────────────────────┼──────────────────────────────
//	codex   │ 退出码 0 即安装证据    │ <config_home>/.codex/config.toml│ 保守 TOML 启发式（见下节）            │ <config_home>/.codex/auth.json 存在
//	        │                       │                                 │                                       │（仅 Lstat 存在性，永不读内容）
//	zcode   │ 同上                  │ <config_home>/.zcode/cli/       │ 全量 JSON 校验：恰一个顶层 JSON 对象， │ setting.json 顶层身份键
//	        │                       │ cli/setting.json（单数文件名，  │ null / 数组 / 尾部多余内容均不命中     │ auth / authToken / credentials
//	        │                       │ 与 localapi/primewire.go 布局   │ （与 primewire 合法性口径同源）        │ 任一存在且非空（值内容不返回）
//	        │                       │ 同源，SPEC 506）                │                                       │
//	其他    │ 仍可探测（宿主无关）   │ —                              │ 一律 fail，原因注明「通用手动」        │ 无 → ExecutionReady 恒不亮
//
// zcode 身份键清单为 V0 保守值（宿主未公开文档化其私有 schema）：清单不命中时
// 按「无登录标记」处理，ExecutionReady 不亮（fail-closed）——绝不因清单不命中
// 而放行，也绝不据此断言「未登录」，仅如实记录标记未发现。codex 的 auth.json
// 存在性同理：只是线索，不验证其有效性。
//
// # 版本输出解析策略
//
// V0 不解析：`--version` 的 stdout+stderr 合流原样留痕（截断上限内逐字节保留），
// 不抽取版本号、不猜格式——宿主 CLI 版本行格式各异且随版本漂移，错误解析比不
// 解析更有害。输出超过捕获上限（默认 64KiB）即截断并注记，且判 Installed=false
// （正常安装的 --version 输出远小于上限，超限即异常信号）。
//
// # 子进程纪律（硬约束）
//
//   - 只运行调用方显式给出的命令，argv 固定为 [<command>, "--version"]：不经
//     shell、不接受调用方附加参数（杜绝参数注入面）；
//   - 超时默认 5s（Options.VersionTimeout 可配），到点 kill 后必 Wait 收尸
//     （防僵尸；WaitDelay 兜底孙进程管道拖住 Wait 的边缘）；
//   - 输出捕获上限默认 64KiB（Options.OutputLimit 可配），超限截断注记，超限
//     后仍持续排空管道（防子进程写阻塞死锁）；
//   - 干净最小 env：仅 PATH（固定最小值）与 LANG=C，不继承进程全量环境（防
//     凭证/代理等环境变量泄漏进子进程）；
//   - 路径存在判定一律 Lstat 不跟随符号链接；symlink 如实注记，不做逃逸展开
//     （探测仍按调用方给出的路径原样执行——exec 由内核解析链接，本包不解析、
//     不声称其他位置）。
//
// # 路径与秘密政策
//
//   - 配置读取三道闸：Lstat 先判符号链接与非普通文件（拒绝即不打开）；打开后
//     以 fd fstat 复核「校验对象=读取对象」（消 Lstat→Open 窗口内的换型）；
//     读取设字节上限并核对实得字节数（防检查后增长拖爆内存）。
//   - 已知限制（V0 如实声明）：Lstat→Open 窗口内被换为另一普通文件的极端时序
//     仍可能读到替换物——本包只回结构判定元数据、内容永不外返，且检测目标是
//     主人受控 config_home（非不可信面），该残窗影响有限；不可信面等级的逐段
//     openat 游走属 inputs 包机制，接线阶段（W06-02）如涉不可信路径应复用
//     inputs.OpenSourceFile，不在本包重复造轮子。
//   - 输出结构体只含元数据（路径引用、存在性、布尔位、--version 输出），配置
//     文件内容、登录凭证内容任何情况下不进结果。
//
// # 本包边界
//
// 不接 localapi、不接 cmd/node、不改既有包（W01-01 §6 禁区）；agentid 是工作区
// 互斥键派生器，不是安装扫描证据，两者勿混用。手工登记永远可用（W06-02 的登记
// 表单不依赖本包检测结论）。
